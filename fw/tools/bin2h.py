#!/usr/bin/env python3
"""Embed the CH559 firmware in the nRF sketch: bin2h.py <kb_bridge_ch559.bin> <build_id> <out.h>"""
import sys

src, build_id, out = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, "rb").read()
bid = int(build_id.rstrip("UL"), 16)
lines = ["// Generated by fw/tools/bin2h.py from %s - do not edit." % src.split("/")[-1],
         "#pragma once",
         "#include <stdint.h>",
         "#define CH559_IMAGE_BUILD_ID 0x%08XUL" % bid,
         "#define CH559_IMAGE_LEN %dUL" % len(data),
         "static const uint8_t CH559_IMAGE[] = {"]
for i in range(0, len(data), 16):
    lines.append("  " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print("%s: %d bytes, build id 0x%08X" % (out, len(data), bid))
